package com.mrh0.createaddition.datagen.Models;

import com.mrh0.createaddition.CreateAddition;
import com.mrh0.createaddition.blocks.electric_motor.ElectricMotorBlock;
import com.tterrag.registrate.providers.DataGenContext;
import com.tterrag.registrate.providers.RegistrateBlockstateProvider;
import com.tterrag.registrate.util.nullness.NonNullBiConsumer;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.Identifier;
import net.minecraft.world.level.block.Block;

public class BlockGenHelper {
    public static NonNullBiConsumer<DataGenContext<Block, ElectricMotorBlock>, RegistrateBlockstateProvider> directionalBlockState(Identifier resourceLocation) {
        return (ctx, prov) -> directionalModel(resourceLocation, ctx, prov);
    }

    public static <T extends Block> NonNullBiConsumer<DataGenContext<Block, T>, RegistrateBlockstateProvider> directionalBlockState() {
        return (ctx, prov) -> directionalModel(Identifier.fromNamespaceAndPath(CreateAddition.MODID, "block/" + getBlockName(ctx.get()) + "/block"), ctx, prov);
    }

    public static NonNullBiConsumer<DataGenContext<Block, ElectricMotorBlock>, RegistrateBlockstateProvider> horizontalBlockState(Identifier resourceLocation) {
        return (ctx, prov) -> horizontalModel(resourceLocation, ctx, prov, 0);
    }

    public static <T extends Block> NonNullBiConsumer<DataGenContext<Block, T>, RegistrateBlockstateProvider> horizontalBlockState() {
        return (ctx, prov) -> horizontalModel(Identifier.fromNamespaceAndPath(CreateAddition.MODID, "block/" + getBlockName(ctx.get()) + "/block"), ctx, prov, 90);
    }

    public static <T extends Block> void directionalModel(Identifier resourceLocation, DataGenContext<Block, T> ctx, RegistrateBlockstateProvider prov) {
        // Runtime builds ship the blockstate JSON generated by the original 1.21.1 project.
    }

    public static <T extends Block> NonNullBiConsumer<DataGenContext<Block, T>, RegistrateBlockstateProvider> simpleBlock(Identifier resourceLocation) {
        return (ctx, prov) -> simpleBlockModel(resourceLocation, ctx, prov);
    }

    public static <T extends Block> NonNullBiConsumer<DataGenContext<Block, T>, RegistrateBlockstateProvider> simpleBlock() {
        return (ctx, prov) -> simpleBlockModel(Identifier.fromNamespaceAndPath(CreateAddition.MODID, "block/" + getBlockName(ctx.get()) + "/block"), ctx, prov);
    }

    public static <T extends Block>  void horizontalModel(Identifier resourceLocation, DataGenContext<Block, T> ctx, RegistrateBlockstateProvider prov, int angleOffset) {
        // Runtime builds ship the blockstate JSON generated by the original 1.21.1 project.
    }

    public static <T extends Block> void simpleBlockModel(Identifier resourceLocation, DataGenContext<Block,T> ctx, RegistrateBlockstateProvider prov) {
        // Runtime builds ship the blockstate JSON generated by the original 1.21.1 project.
    }

    public static String getBlockName(Block block) {
        return  BuiltInRegistries.BLOCK.getKey(block).getPath();
    }
}
